BEGIN;

CREATE SCHEMA IF NOT EXISTS storytech;

DROP FUNCTION IF EXISTS storytech.increment_article_views(text);
DROP TABLE IF EXISTS storytech.articles CASCADE;
DROP TABLE IF EXISTS storytech.issues CASCADE;
DROP TABLE IF EXISTS storytech.stories CASCADE;
DROP TABLE IF EXISTS storytech.access_keys CASCADE;

-- ---------------------------------------------------------------------
-- access_keys: 발급된 접속 키 (원래 키는 저장하지 않고 SHA-256 해시만)
-- ---------------------------------------------------------------------
CREATE TABLE storytech.access_keys (
  key_hash   text        PRIMARY KEY CHECK (key_hash ~ '^[0-9a-f]{64}$'),
  age        smallint    NOT NULL CHECK (age BETWEEN 1 AND 120),
  gender     text        NOT NULL CHECK (gender IN ('male', 'female', 'other')),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- stories: 스토리 메타데이터 (본문은 IPFS에 암호문으로만 존재)
--   wrapped_key: 스토리별 데이터 키를 마스터키(STORY_ENCRYPTION_KEY)로 암호화한 값
--                이 행을 삭제하면 IPFS 암호문은 영구히 복호화 불가
--   publish_consent / pen_name: 학생이 제출 시 직접 선택한 매거진 게재 동의와 공개용 필명
--                (접속 키의 나이·성별과는 연결하지 않음)
-- ---------------------------------------------------------------------
CREATE TABLE storytech.stories (
  id              uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  cid             text        NOT NULL UNIQUE,
  wrapped_key     text        NOT NULL,
  emotions        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  keywords        text[]      NOT NULL DEFAULT '{}',
  input_type      text        NOT NULL CHECK (input_type IN ('voice', 'text')),
  publish_consent boolean     NOT NULL DEFAULT false,
  pen_name        text        CHECK (char_length(btrim(pen_name)) BETWEEN 1 AND 30),
  created_at      timestamptz NOT NULL DEFAULT now(),
  CHECK (pen_name IS NULL OR publish_consent)
);

CREATE INDEX stories_created_at_idx ON storytech.stories (created_at DESC);

-- ---------------------------------------------------------------------
-- issues / articles: 매거진 (관리자가 편집하는 공개 콘텐츠)
-- ---------------------------------------------------------------------
CREATE TABLE storytech.issues (
  id           text        PRIMARY KEY DEFAULT gen_random_uuid()::text,
  issue_number integer     NOT NULL UNIQUE,
  title        text        NOT NULL,
  theme        text        NOT NULL DEFAULT '',
  editor_note  text        NOT NULL DEFAULT '',
  is_published boolean     NOT NULL DEFAULT false,
  published_at timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CHECK (NOT is_published OR published_at IS NOT NULL)
);

CREATE TABLE storytech.articles (
  id            text        PRIMARY KEY DEFAULT gen_random_uuid()::text,
  issue_id      text        NOT NULL REFERENCES storytech.issues (id) ON DELETE CASCADE,
  type          text        NOT NULL CHECK (type IN ('interview', 'story', 'review')),
  title         text        NOT NULL,
  content       text        NOT NULL DEFAULT '',
  author_name   text        NOT NULL DEFAULT '익명',
  display_order integer     NOT NULL DEFAULT 1,
  views         integer     NOT NULL DEFAULT 0 CHECK (views >= 0),
  -- 임팩트 섹션 "학생들의 목소리"에 쓰이는 인용문 — 본문에 실제로 있는 문장만 허용
  highlight_quote text      CHECK (char_length(btrim(highlight_quote)) BETWEEN 1 AND 300),
  created_at    timestamptz NOT NULL DEFAULT now(),
  CHECK (highlight_quote IS NULL OR strpos(content, highlight_quote) > 0)
);

CREATE INDEX articles_issue_id_idx ON storytech.articles (issue_id, display_order);

-- 조회수 원자적 증가 (동시 요청에도 누락 없음)
CREATE FUNCTION storytech.increment_article_views(p_article_id text)
RETURNS integer
LANGUAGE sql
SET search_path = ''
AS $$
  UPDATE storytech.articles
  SET views = views + 1
  WHERE id = p_article_id
  RETURNING views;
$$;

-- ---------------------------------------------------------------------
-- 권한: service_role 전용
-- ---------------------------------------------------------------------
ALTER TABLE storytech.access_keys ENABLE ROW LEVEL SECURITY;
ALTER TABLE storytech.stories     ENABLE ROW LEVEL SECURITY;
ALTER TABLE storytech.issues      ENABLE ROW LEVEL SECURITY;
ALTER TABLE storytech.articles    ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON SCHEMA storytech FROM anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA storytech FROM anon, authenticated;
REVOKE EXECUTE ON FUNCTION storytech.increment_article_views(text) FROM PUBLIC, anon, authenticated;

GRANT USAGE ON SCHEMA storytech TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA storytech TO service_role;
GRANT EXECUTE ON FUNCTION storytech.increment_article_views(text) TO service_role;

