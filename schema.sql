-- 실행 방법
--   1. Supabase Dashboard → SQL Editor → New query → 이 파일 전체 붙여넣기 → Run
--   2. Project Settings → Data API → Exposed schemas 에 storytech 추가 → Save
--
-- 접근 정책
--   - 모든 테이블 RLS 활성화 + 정책 없음 → anon / authenticated 키로는 접근 불가
--   - 서버(Route Handler)만 service_role 키로 접근
--
-- 주의: 재실행하면 storytech 스키마의 모든 테이블이 초기화됩니다.
